<?php

namespace App\Enums;

/** Способ включения одной финансовой операции в проектную аналитику. */
enum FinanceAllocationKind
{
    /** Операция имеет project_id и её проект входит в текущий срез отчёта. */
    case DIRECT;

    /** Операция не имеет project_id, но должна быть разделена между проектами. */
    case DISTRIBUTED;

    /** Расход не имеет ни project_id, ни настройки проектного распределения. */
    case UNDISTRIBUTED;

    /** Доход не имеет проекта и учитывается только в отчёте всей компании. */
    case GLOBAL;

    /** Операция не относится к проектам текущего среза и не должна рассчитываться. */
    case EXCLUDED;
}
