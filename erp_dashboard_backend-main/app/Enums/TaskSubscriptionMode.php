<?php

namespace App\Enums;

/**
 * Личный режим уведомлений по задаче: «Следить» добавляет связь «Наблюдатель», «Не уведомлять» отключает всё по задаче.
 */
enum TaskSubscriptionMode: string
{
    case WATCH = 'watch';
    case MUTE = 'mute';
    // «По участию», выбранное вместо «Следить»: строка остаётся, чтобы автоподписка не включила слежение снова. Наружу — null.
    case NONE = 'none';
}
